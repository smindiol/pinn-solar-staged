needs_base_b = pytest.mark.skipif(not (data_m.local_root() / data_m.SPLIT_FILE).exists(),
                                  reason="base_b not available")
S = Scales()


@pytest.fixture(scope="module")
def rows():
    return data_m.read_split(data_m.local_root(), origins=None)


@pytest.fixture(scope="module")
def refs(rows):
    s = data_m.split_m(data_m.local_root(), rows)
    return {r.uid: r for r in s.train + s.val + s.test}


def _first(rows, origin, material):
    r = next(r for r in rows if r["origin"] == origin and r["material"] == material)
    return f"{r['material']}/{r['group']}", r


#: one device per origin (and the materials beyond E1gen), the unit check of S3
ORIGINS = [("E1A", "E1gen"), ("E1B", "E1gen"), ("dpvB2", "E1gen"), ("dpvB2", "Si"), ("dpvB1_cancelled", "InP")]


@needs_base_b
def test_base_m_keeps_only_the_dpvB2_devices_by_default() -> None:
    """Operator 2026-11-15: network M trains and is evaluated on the devices generated by dpvB2 only; the E1A, E1B
    and dpvB1_cancelled origins cover another parameter region (tau 1e-8, Eg varying) and leave base M."""
    rows = data_m.read_split(data_m.local_root())
    assert {r["origin"] for r in rows} == {"dpvB2"} and data_m.TRAIN_ORIGINS == ("dpvB2",)
    s = data_m.split_m(data_m.local_root(), rows)
    assert (len(s.train), len(s.val), len(s.test)) == (1384, 175, 172)
    assert {r.material for r in s.train} == set(data_m.MATERIALS)
    assert max(r.n_V for r in s.train) == 29


